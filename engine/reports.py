# ALLOCATION PIE CHART
# ==========================================================

def allocation_chart(portfolio):
    """
    Portfolio allocation pie chart.
    """

    labels = [
        p["asset"]
        for p in portfolio
    ]

    sizes = [
        p["allocation_pct"]
        for p in portfolio
    ]

    fig, ax = plt.subplots(figsize=(7,7))

    ax.pie(

        sizes,

        labels=labels,

        autopct="%1.1f%%",

        startangle=90

    )

    ax.set_title(
        "Portfolio Allocation"
    )

    buf = io.BytesIO()

    fig.savefig(
        buf,
        format="png",
        bbox_inches="tight"
    )

