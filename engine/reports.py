# PORTFOLIO GROWTH CHART
# ==========================================================

def chart(curve):
    """
    Portfolio growth chart.
    Returns a base64 PNG image.
    """

    fig, ax = plt.subplots(figsize=(10, 5))

    fig.patch.set_facecolor("#0b0f19")
    ax.set_facecolor("#0b0f19")

    x = np.arange(len(curve))
    y = np.array(curve)

    ax.plot(
        x,
        y,
        linewidth=2,
        color="#60a5fa"
    )

    ax.fill_between(
        x,
        y,
        alpha=0.20,
        color="#60a5fa"
    )

    ax.set_title(
        "Portfolio Growth",
        color="white",
        fontsize=14
    )

    ax.set_xlabel(
        "Months",
        color="white"
    )

    ax.set_ylabel(
        "Portfolio Value (KES)",
        color="white"
    )

    ax.grid(
        alpha=0.25
    )

    ax.tick_params(colors="white")

    ax.spines["bottom"].set_color("#334155")
    ax.spines["left"].set_color("#334155")
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    buf = io.BytesIO()

    fig.savefig(
        buf,
        format="png",
        dpi=120,
        bbox_inches="tight"
    )

    plt.close(fig)

    buf.seek(0)

    return base64.b64encode(
        buf.read()
    ).decode()


