# DIVIDEND REPORT
# ==========================================================

def dividend_report(portfolio):
    """
    Dividend income by company.
    """

    rows = []

    total = 0

    for asset in portfolio:

        dividend = asset.get(
            "dividends",
            0
        )

        total += dividend

        rows.append({

            "company":
                asset.get("asset", ""),

            "dividend":
                money(dividend),

            "yield":
                percent(
                    asset.get(
                        "dividend_yield",
                        0
                    )
                )

        })

    return {

        "companies": rows,

        "total_dividends":
            money(total)

    }


