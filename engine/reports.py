# ==========================================================
# CURRENCY FORMATTER
# ==========================================================

def money(value):

    """
    Formats values as Kenyan Shillings.
    """

    try:

        return f"{DEFAULT_CURRENCY} {float(value):,.2f}"

    except Exception:

        return f"{DEFAULT_CURRENCY} 0.00"


# ==========================================================
# PERCENTAGE FORMATTER
# ==========================================================

def percent(value):

    """
    Formats percentage values.
    """

    try:

        return f"{float(value):.2f}%"

    except Exception:

        return "0.00%"


# ==========================================================
# NUMBER FORMATTER
# ==========================================================

def number(value, decimals=2):

    """
    Generic numeric formatter.
    """

    try:

        return round(float(value), decimals)

    except Exception:

        return 0.0


