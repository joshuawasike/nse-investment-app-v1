# SECTOR BREAKDOWN
# ==========================================================

def sector_breakdown(portfolio):
    """
    Portfolio allocation by sector.
    """

    sectors = {}

    for asset in portfolio:

        sector = asset.get(
            "sector",
            "Unknown"
        )

        allocation = asset.get(
            "allocation_pct",
            0
        )

        sectors[sector] = (
            sectors.get(sector, 0)
            + allocation
        )

    rows = []

    for sector, allocation in sectors.items():

        rows.append({

            "sector": sector,

            "allocation":
                percent(allocation)

        })

    return rows


