def sector_chart(portfolio):
    """
    Sector allocation chart.
    """

    sectors = {}

    for asset in portfolio:

        sector = asset.get(
            "sector",
            "Unknown"
        )

        sectors[sector] = (

            sectors.get(
                sector,
                0
            )

            +

            asset.get(
                "allocation_pct",
                0
            )

        )

    labels = list(
        sectors.keys()
    )

    values = list(
        sectors.values()
    )

    fig, ax = plt.subplots(
        figsize=(8,5)
    )

    ax.bar(
        labels,
        values
    )

    ax.set_ylabel(
        "Allocation (%)"
    )

    ax.set_title(
        "Sector Allocation"
    )

    plt.xticks(
        rotation=25
    )

    buf = io.BytesIO()

    fig.savefig(
        buf,
        format="png",
        bbox_inches="tight"
    )

    plt.close(fig)

    buf.seek(0)

    return base64.b64encode(
        buf.read()
    ).decode()


