# ASSET STATISTICS
# ==========================================================

def asset_statistics(portfolio):
    """
    Portfolio statistics.
    """

    if not portfolio:

        return {}

    total_assets = len(portfolio)

    total_value = sum(

        asset.get(
            "current_value",
            0
        )

        for asset in portfolio

    )

    total_income = sum(

        asset.get(
            "dividends",
            0
        )

        for asset in portfolio

    )

    return {

        "companies":

            total_assets,

        "portfolio_value":

            money(total_value),

        "dividend_income":

            money(total_income),

        "average_value":

            money(
                total_value /
                total_assets
            )

    }


